const fs = require('fs');
const path = require('path');
const ejs = require('ejs');

const viewsDir = path.join(__dirname, '../views');
const pagesDir = path.join(viewsDir, 'pages');
const internalDir = path.join(__dirname, '../internal/html');

const templates = {};

// Blog nav static string
const navPath = path.join(internalDir, 'blog_nav.html');
templates['blog_nav'] = fs.existsSync(navPath) ? fs.readFileSync(navPath, 'utf8') : '';

// Index template
const indexPath = path.join(viewsDir, 'index.ejs');
if (fs.existsSync(indexPath)) {
  templates['index'] = fs.readFileSync(indexPath, 'utf8');
}

// Pages
if (fs.existsSync(pagesDir)) {
  const files = fs.readdirSync(pagesDir);
  for (const file of files) {
    if (file.endsWith('.ejs') || file.endsWith('.html')) {
      const key = 'pages/' + file.replace(/\.(ejs|html)$/, '');
      templates[key] = fs.readFileSync(path.join(pagesDir, file), 'utf8');
    }
  }
}

const { execSync } = require('child_process');
let commitSha = 'release';
try {
  commitSha = execSync('git rev-parse --short HEAD').toString().trim();
} catch (e) {}

const now = new Date();
const buildNumber = `${now.getFullYear()}.${String(now.getMonth() + 1).padStart(2, '0')}.${String(now.getDate()).padStart(2, '0')}-${commitSha}`;
const buildTime = now.toISOString().replace('T', ' ').slice(0, 19) + ' UTC';

// 1. Output legacy CommonJS strings
const outContent = `// Auto-generated by scripts/build-templates.js
module.exports = ${JSON.stringify(templates, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '../lib/template-strings.js'), outContent, 'utf8');
fs.writeFileSync(path.join(__dirname, '../lib/build-info.json'), JSON.stringify({ buildNumber, buildTime }, null, 2), 'utf8');

// 2. Precompile all EJS templates into pure standalone JS functions (zero eval / zero new Function / zero with statements)
const destructuredLocals = [
  'data', 'product', 'sections', 'banners', 'products',
  'categories', 'brands', 'page', 'content', 'pageContent', 'useEjs', 'err',
  'center_content', 'bottom_footer', 'bottom_nav', 'bottom_content',
  'prescription_category', 'prescription_products', 'plano_category', 'plano_products',
  'buildNumber', 'buildTime'
];

const compiledEntries = [];
for (const key of Object.keys(templates)) {
  if (key !== 'blog_nav' && templates[key]) {
    try {
      const fnStr = ejs.compile(templates[key], {
        client: true,
        compileDebug: false,
        _with: false,
        destructuredLocals,
      }).toString();
      compiledEntries.push(`${JSON.stringify(key)}: ${fnStr}`);
    } catch (err) {
      console.warn(`Warning: failed to client-compile ${key}:`, err.message);
    }
  }
}

const compiledCode = `// Auto-generated by scripts/build-templates.js
// Precompiled at build-time for Cloudflare Workers (zero runtime eval / zero with-statement)

export const rawBlogNavContent: string = ${JSON.stringify(templates['blog_nav'] || '')};
export const buildNumber: string = ${JSON.stringify(buildNumber)};
export const buildTime: string = ${JSON.stringify(buildTime)};

export const compiledTemplates: Record<string, (locals: any) => string> = {
  ${compiledEntries.join(',\n  ')}
};

export default compiledTemplates;
`;

fs.writeFileSync(path.join(__dirname, '../server/utils/compiled-templates.ts'), compiledCode, 'utf8');

console.log(`Precompiled ${compiledEntries.length} templates strictly as ESM for Cloudflare Pages!`);
